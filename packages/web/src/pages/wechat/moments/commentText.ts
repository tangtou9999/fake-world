import type { Descendant } from "slate";

export const AUTO_GENERATED_COMMENT_TEXT = "这是自动生成的评论，进入编辑模式进行修改或删除";

export function slatePlainText(nodes: Descendant[] | undefined): string {
	if (!nodes) return "";
	return nodes
		.map((node) => {
			if ("text" in node && typeof node.text === "string") return node.text;
			if ("children" in node && Array.isArray(node.children)) {
				return slatePlainText(node.children as Descendant[]);
			}
			return "";
		})
		.join("");
}

export function isAutoGeneratedCommentText(nodes: Descendant[] | undefined) {
	return slatePlainText(nodes).trim() === AUTO_GENERATED_COMMENT_TEXT;
}
